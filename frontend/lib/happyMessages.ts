const lastShownIndex: Partial<Record<MessageContext, number>> = {};

export function getRandomMessage(context: MessageContext): string {
  const messages = happyMessages[context];
  let index: number;
  do {
    index = Math.floor(Math.random() * messages.length);
  } while (index === lastShownIndex[context] && messages.length > 1);
  lastShownIndex[context] = index;
  return messages[index];
}
